export type TerminalInputKind = "agent" | "terminal"

export interface TerminalKeyEventLike {
  key: string
  altKey: boolean
  ctrlKey: boolean
  metaKey: boolean
  shiftKey: boolean
  isComposing: boolean
  type: string
}

export interface TerminalKeyContext {
  platform: string
  inputKind: TerminalInputKind
}

const ESCAPE_DELETE = "\u001b\u007f"
const DELETE_TO_LINE_START = "\u0015"
const SHIFT_ENTER_CSI_U = "\u001b[13;2u"
const QUOTED_LITERAL_LINE_FEED = "\u0016\n"

/**
 * Map only the macOS editing combinations xterm cannot infer from PTY context.
 * A null result delegates untouched to xterm, preserving ordinary shortcuts,
 * paste, IME composition, and the default CR generated by plain Enter.
 */
export function mapTerminalKeyEvent(
  event: TerminalKeyEventLike,
  context: TerminalKeyContext,
): string | null {
  if (context.platform !== "darwin" || event.type !== "keydown" || event.isComposing) return null

  const isCommandDelete =
    event.key === "Backspace" && event.metaKey && !event.altKey && !event.ctrlKey && !event.shiftKey
  if (isCommandDelete) return DELETE_TO_LINE_START
  const isOptionDelete =
    event.key === "Backspace" && event.altKey && !event.ctrlKey && !event.metaKey && !event.shiftKey
  if (isOptionDelete) return ESCAPE_DELETE

  const isUnmodifiedShiftEnter =
    event.key === "Enter" && event.shiftKey && !event.altKey && !event.ctrlKey && !event.metaKey
  if (!isUnmodifiedShiftEnter) return null
  return context.inputKind === "agent" ? SHIFT_ENTER_CSI_U : QUOTED_LITERAL_LINE_FEED
}
